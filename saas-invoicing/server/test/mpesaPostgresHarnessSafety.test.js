const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const serverRoot = path.resolve(__dirname, '..')
const harnessPath = path.join(serverRoot, 'integration', 'mpesa-postgres.js')
const harness = fs.readFileSync(harnessPath, 'utf8')
const readIntegrationFile = (name) => fs.readFileSync(path.join(serverRoot, 'integration', name), 'utf8')

test('M-Pesa PostgreSQL harness requires its dedicated fixed loopback target', () => {
  assert.match(harness, /process\.env\.MPESA_TEST_DATABASE_URL/)
  assert.match(harness, /MPESA_TEST_DATABASE_CONFIRMATION/)
  assert.match(harness, /I_CONFIRM_THIS_IS_A_DISPOSABLE_MPESA_TEST_DATABASE/)
  assert.match(harness, /invoxa_mpesa_test_local/)
  assert.match(harness, /invoxa_mpesa_test_role/)
  assert.match(harness, /parsed\.hostname !== '127\.0\.0\.1'/)
  assert.match(harness, /parsed\.port !== '5432'/)
  assert.match(harness, /server_is_approved_loopback/)
  assert.match(harness, /server_port_is_approved/)
  assert.match(harness, /has_required_pg_version/)
  assert.match(harness, /name\.toUpperCase\(\) === 'DATABASE_URL' \|\| \/\^PG/)
  assert.doesNotMatch(harness, /require\(['"]dotenv['"]\)|require\([^)]*\.env|process\.env\.DATABASE_URL\s*(?:\|\||\?\?)/)
})

test('M-Pesa harness refuses unsafe database privileges and non-empty targets before DDL', () => {
  assert.match(harness, /DATABASE_COMMENT = 'INVOXA_DISPOSABLE_MPESA_TEST'/)
  assert.match(harness, /role_has_unneeded_privilege/)
  assert.match(harness, /database_temp/)
  assert.match(harness, /owns_public_schema/)
  assert.match(harness, /owns_uuid_ossp/)
  assert.match(harness, /owns_uuid_generator/)
  assert.match(harness, /uuid_ossp_prerequisite_missing/)
  assert.match(harness, /plpgsql_language_prerequisite_missing/)
  assert.match(harness, /async function verifyEmptyTarget/)
  assert.match(harness, /pg_event_trigger/)
  assert.match(harness, /unexpectedExtensions/)
  assert.match(harness, /relation_type\.oid IS NULL/)
  assert.match(harness, /await verifyEmptyTarget\(lockClient\)/)
  assert.match(harness, /if \(!disposableTargetVerified \|\| !objectsMayExist \|\| !lockClient \|\| !advisoryLockHeld\) return/)
  assert.match(harness, /RUN_OBJECT_MARKER = `INVOXA_MPESA_IT_RUN_/)
  assert.match(harness, /includeRunMarkersInMigration\(migration\.sql, migration\.objects\)/)
  assert.match(harness, /hasRunMarker\(lockClient, 'table', tableName\)/)
  assert.match(harness, /hasRunMarker\(lockClient, 'function', functionName\)/)
  assert.match(harness, /DROP TABLE public\.\$\{tableName\}/)
  assert.doesNotMatch(harness, /DROP\s+(?:DATABASE|SCHEMA)\b/i)
})

test('integration harness stays opt-in and its launcher strips inherited database settings', () => {
  const packageJson = JSON.parse(fs.readFileSync(path.join(serverRoot, 'package.json'), 'utf8'))
  assert.equal(packageJson.scripts.test, 'node --test')
  assert.equal(packageJson.scripts['test:mpesa:integration'], 'node --test integration/mpesa-postgres.js')
  assert.notEqual(path.dirname(harnessPath), path.join(serverRoot, 'test'))

  const launcher = readIntegrationFile('run-mpesa-postgres.ps1')
  assert.match(launcher, /Where-Object \{ \$_.Name -ieq 'DATABASE_URL' -or \$_.Name -like 'PG\*' \}/)
  assert.match(launcher, /MPESA_TEST_DATABASE_URL/)
  assert.match(launcher, /127\.0\.0\.1:5432\/invoxa_mpesa_test_local/)
  assert.doesNotMatch(launcher, /\.env|DATABASE_URL\s*\|\|/i)

  const fixture = readIntegrationFile('mpesa-payments-fixture.sql')
  assert.match(fixture, /SYNTHETIC TEST FIXTURE ONLY/)
  assert.match(harness, /provider = acceptedProvider\(\)/)
  assert.doesNotMatch(harness, /require\(['"](?:axios|\.\.\/.*daraja|\.\.\/.*mpesaConfig)['"]\)/i)
})
